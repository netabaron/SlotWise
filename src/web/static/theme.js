/* =========================================================================
 * theme.js — קובע את ערכת הצבעים לפני הציור הראשון.
 *
 * למה קובץ נפרד, ולמה הוא נטען **בלי** defer בתוך <head>:
 * זהו הסקריפט היחיד שחייב לרוץ לפני שהדפדפן מצייר משהו. אם בחרו "בהיר"
 * בזמן שמערכת ההפעלה כהה, וההחלה מתרחשת אחרי הציור הראשון — העמוד מהבהב
 * כהה ואז מתהפך. ‏app.js נטען עם defer, כלומר עלול לרוץ אחרי הציור, ולכן
 * הוא אינו המקום לזה.
 *
 * ולמה לא סקריפט מוטבע ב-HTML: ‏templates/index.html מצהיר שאין בו שום
 * לוגיקה ושום קוד מוטבע. קובץ סטטי קטן שומר על ההצהרה הזאת.
 *
 * מה הוא עושה, וזה הכל: אם נשמרה בחירה מפורשת — מסמן אותה על <html>.
 * "לפי המערכת" נשמר כהיעדר ערך, ואז אין תכונה כלל וגיליון הסגנון מחליט
 * לפי ‎prefers-color-scheme‎ — כולל שינוי של מערכת ההפעלה בזמן שהעמוד פתוח,
 * בלי שורת JavaScript אחת שמאזינה לזה.
 * ========================================================================= */

(function () {
  "use strict";

  var KEY = "slotwise_theme";

  try {
    var saved = window.localStorage.getItem(KEY);
    if (saved === "light" || saved === "dark") {
      document.documentElement.setAttribute("data-theme", saved);
    }
  } catch (e) {
    /* חלון פרטי או אחסון חסום — נשארים עם הגדרת מערכת ההפעלה. */
  }
})();
